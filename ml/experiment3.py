#!/usr/bin/env python3
"""NEXUS ML experiment 3: larger embedding models, top-2 accuracy, and a learning curve.

Builds on experiment 2 (same gold set, same folds, same weak data). Only the linear/centroid models that won
experiment 2 are kept; Random Forest and XGBoost were the weakest models there on every feature set.
Top-2 accuracy: the gold label is among the model's two highest-scoring domains - relevant because NEXUS can
tag an item with two domains and many items genuinely span two (e.g. AI + hardware).
Learning curve: protocol-A accuracy when training on 25/50/75/100% of the gold training folds, to estimate
whether labelling more items is worth it.
"""
import sys
import time
from collections import Counter
from pathlib import Path

import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, f1_score
from sklearn.model_selection import GroupKFold, RepeatedStratifiedKFold
from sklearn.svm import LinearSVC

sys.path.insert(0, str(Path(__file__).resolve().parent))
import experiment2 as E  # noqa: E402

E.EMB_MODELS.update({"BGE-base": "BAAI/bge-base-en-v1.5", "MPNet": "sentence-transformers/all-mpnet-base-v2"})
SEED = 42


def topk_acc(scores, classes, y, k=2):
    top = np.argsort(-scores, axis=1)[:, :k]
    return float(np.mean([y[i] in classes[top[i]] for i in range(len(y))]))


def evaluate(F, y, grp, Gn, splits, weak, make, ev, frac=1.0, rng=None):
    f1, acc, top2 = [], [], []
    for tr, te in splits:
        if frac < 1.0:
            tr = rng.choice(tr, size=max(20, int(len(tr) * frac)), replace=False)
        idx = tr
        if weak:
            held = set(grp[te])
            idx = np.concatenate([tr, np.arange(Gn, len(y))[[g not in held for g in grp[Gn:]]]])
        m = make().fit(F[idx], y[idx])
        p = m.predict(F[te])
        f1.append(f1_score(y[te], p, labels=ev, average="macro", zero_division=0))
        acc.append(accuracy_score(y[te], p))
        s = m.decision_function(F[te]) if hasattr(m, "decision_function") else None
        if s is not None:
            top2.append(topk_acc(s, m.classes_, y[te]))
    return dict(f1=np.mean(f1), f1_sd=np.std(f1), acc=np.mean(acc), acc_sd=np.std(acc),
                top2=np.mean(top2) if top2 else float("nan"))


def main():
    G, W, desc, N = E.load_all()
    yG = G["y"]; Gn = len(yG); c = Counter(yG)
    ev = sorted(d for d, n in c.items() if n >= E.MIN_EVAL)
    y = np.concatenate([yG, W["y"]]); grp = np.concatenate([G["src"], W["src"]])
    strat = np.array([x if c[x] >= 5 else "_rare" for x in yG])
    A = list(RepeatedStratifiedKFold(n_splits=5, n_repeats=3, random_state=SEED).split(np.zeros(Gn), strat))
    B = list(GroupKFold(n_splits=5).split(np.zeros(Gn), yG, G["src"]))
    texts = G["X"] + W["X"]
    models = {"Logistic regression": lambda: LogisticRegression(max_iter=4000, C=10, class_weight="balanced"),
              "Linear SVM": lambda: LinearSVC(C=1, class_weight="balanced")}
    lines = []
    for emb in ("MiniLM", "BGE-small", "BGE-base", "MPNet"):
        t0 = time.time()
        F = E.embed(emb, texts, "items")
        print(f"[{emb}] embeddings ready ({time.time() - t0:.0f}s)", flush=True)
        for mname, mk in models.items():
            for proto, sp in (("A", A), ("B", B)):
                for weak in (False, True):
                    r = evaluate(F, y, grp, Gn, sp, weak, mk, ev)
                    tag = "G+W" if weak else "G"
                    line = (f"| {emb} | {mname} | {proto} | {tag} | {r['acc']:.3f} ± {r['acc_sd']:.3f} | {r['top2']:.3f} | "
                            f"{r['f1']:.3f} ± {r['f1_sd']:.3f} |")
                    print(line, flush=True); lines.append((emb, mname, proto, tag, r, line))
    best = max((l for l in lines if l[2] == "B"), key=lambda l: l[4]["acc"])
    emb, mname = best[0], best[1]
    F = E.embed(emb, texts, "items")
    rng = np.random.default_rng(SEED)
    curve = []
    for frac in (0.25, 0.5, 0.75, 1.0):
        r = evaluate(F, y, grp, Gn, A, False, models[mname], ev, frac, rng)
        curve.append(f"| {int(frac * 100)}% (~{int(frac * Gn * 0.8)} items) | {r['acc']:.3f} | {r['top2']:.3f} | {r['f1']:.3f} |")
        print(curve[-1], flush=True)
    rep = ["# Experiment 3 - larger embeddings, top-2 accuracy, learning curve", "",
           f"Generated by `ml/experiment3.py` on {time.strftime('%Y-%m-%d %H:%M')}. Same gold set and folds as experiment 2.", "",
           "Protocol A = repeated stratified 5-fold CV (15 folds). Protocol B = whole feeds held out (5 folds).",
           "Top-2 = gold label among the two highest-scoring domains.", "",
           "| Embeddings | Model | Protocol | Training | Accuracy | Top-2 accuracy | Macro-F1 |", "|---|---|---|---|---|---|---|"]
    rep += [l[5] for l in sorted(lines, key=lambda l: (l[2], -l[4]["acc"]))]
    rep += ["", f"## Learning curve ({emb} + {mname}, protocol A, gold only)", "",
            "| Gold training data | Accuracy | Top-2 | Macro-F1 |", "|---|---|---|---|"] + curve
    out = E.ML / "reports" / "experiment3.md"
    out.write_text("\n".join(rep) + "\n", encoding="utf-8")
    print(f"\nbest on unseen feeds: {emb} + {mname} acc {best[4]['acc']:.3f} top2 {best[4]['top2']:.3f}\nreport: {out}")


if __name__ == "__main__":
    main()
